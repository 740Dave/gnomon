def test_group_by_recommended_x_chosen_and_cross_binned_by_day_with_the_old_nodes_counted(tmp_path):
    corpus = str(tmp_path / "dsd-answers.lts")
    w = LtsFileDecisionWriter(corpus)
    doc = parse_dsd(TWO)
    oct4 = 1_790_000_000.0 - 86400            # 2026-10-04T... UTC
    f4 = {"sent_epoch": oct4 - 60, "answered_epoch": oct4}
    f5 = {"sent_epoch": oct4 + 86400 - 60, "answered_epoch": oct4 + 86400}
    w.mint(mint_dsd_nodes("dsd-1a0e000001", "a", doc.decisions, answers(), decided_on="2026-10-04", answer_fields=f4))
    w.mint(mint_dsd_nodes("dsd-1a0e000002", "a", doc.decisions, answers(), decided_on="2026-10-05", answer_fields=f5))
    w.mint(mint_dsd_nodes("dsd-1a0e000007", "a", doc.decisions,
                          {"D1": DecisionAnswer(labels=["No"], comment=""), "D2": DecisionAnswer(labels=["Later"], comment="")},
                          decided_on="2026-10-05", answer_fields=f5))
    w.mint(mint_dsd_nodes("dsd-1a0e000009", "a", doc.decisions, answers(), decided_on="2026-10-03"))        # minted before the fields
    agg = AS.group_counts(corpus)
    assert agg["total"] == 8 and agg["with_fields"] == 6 and agg["without_fields"] == 2
    # D1 recommended Yes (1): chose Yes (1) in DSDs 1 and 2. D2 recommended Now (1): chose Later (2) in all three DSDs; DSD 3's D1 chose No (2).
    assert agg["groups"] == {("1", "1"): 2, ("1", "2"): 4}
    by_day = AS.group_counts(corpus, by_day=True)
    d4 = time.strftime("%Y-%m-%d", time.gmtime(oct4))
    d5 = time.strftime("%Y-%m-%d", time.gmtime(oct4 + 86400))
    assert by_day["groups"][("1", "1", d4)] == 1 and by_day["groups"][("1", "1", d5)] == 1
    assert sum(by_day["groups"].values()) == 6 and by_day["without_fields"] == 2 and by_day["zone"] == "UTC"


def test_the_same_answers_binned_by_utc_and_by_los_angeles_across_a_midnight(tmp_path):
    """D-F4: the day an answer falls in depends on the zone the ANALYST states; the node carries the UTC instant."""
    corpus = str(tmp_path / "dsd-answers.lts")
    doc = parse_dsd(TWO)
    # 2026-10-06T06:30:00Z = 2026-10-05 23:30 in Los Angeles (UTC-7): the SAME instant, two different days
    inst = calendar.timegm((2026, 10, 6, 6, 30, 0))
    LtsFileDecisionWriter(corpus).mint(mint_dsd_nodes("dsd-1a0e000001", "a", doc.decisions, answers(), decided_on="2026-10-05",
                                                     answer_fields={"sent_epoch": inst - 60, "answered_epoch": inst}))
    node = AS.read_decision_nodes(corpus)["nodes"][0]["props"]
    assert node["answered-at"] == "2026-10-06T06:30:00Z"
    utc = AS.group_counts(corpus, by_day=True)
    la = AS.group_counts(corpus, by_day=True, zone="America/Los_Angeles")
    assert {k[-1] for k in utc["groups"]} == {"2026-10-06"} and {k[-1] for k in la["groups"]} == {"2026-10-05"}
    assert la["zone"] == "America/Los_Angeles" and utc["day_from_decided_in_session"] == 0
    with pytest.raises(Exception):
        AS.group_counts(corpus, by_day=True, zone="Not/AZone")


def test_a_node_without_answered_at_falls_back_to_its_decided_date_and_is_counted(tmp_path):
    corpus = str(tmp_path / "dsd-answers.lts")
    doc = parse_dsd(TWO)
    nodes = mint_dsd_nodes("dsd-1a0e000001", "a", doc.decisions, answers(), decided_on="2026-10-05",
                           answer_fields={"sent_epoch": 1.0, "answered_epoch": 9.0})
    for n in nodes:
        n.properties.pop("answered-at", None)
    LtsFileDecisionWriter(corpus).mint(nodes)
    assert AS.group_counts(corpus, by_day=True)["without_fields"] == 2          # answered-at is one of the field keys: counted as old


def test_answered_at_is_a_utc_iso_scalar_with_z():
    p = {n.node_id: n.properties for n in mint(fields={"sent_epoch": 0.0, "answered_epoch": 1_790_000_000.0})}
    v = p["DEC-DSD-1A0E00000A-D1"]["answered-at"]
    assert re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", v) and v == time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(1_790_000_000.0))


