"""Render a SkillProjection to a SKILL.md file, and read back the ownership/drift stamps.

Emitted file (``~/.claude/skills/<skill-name>/SKILL.md``):

    ---
    name: <skill-name>
    description: <skill-desc>
    user-invocable: true
    generated-from: <node-id>@<corpus>
    source-hash: <sha256 of the node's skill-* fields>
    ---
    <do-not-hand-edit banner>
    # <skill-name>
    Generated projection of [<node-id>] in corpus `<corpus>`.
    <trigger + resolved pointers + subset note>

The two stamps are how the generator (a) knows it OWNS the file (``generated-from``) and
(b) detects the source node drifting (``source-hash``). A file WITHOUT ``generated-from`` is
hand-authored and MUST NOT be touched (constraint 2).
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass

from .contract import SkillProjection

STAMP_GENERATED_FROM = "generated-from"
STAMP_SOURCE_HASH = "source-hash"

_DO_NOT_EDIT = (
    "<!-- GENERATED FILE — do not hand-edit. Regenerated by "
    "Gnomon `sync_my_skills` / `python -m gnomon.skills` from the projection-contract node stamped in the "
    "frontmatter (generated-from). Edit the node in the graph, not this file. -->"
)

# Human labels for the resolved pointer fields.
_POINTER_LABEL = {
    "skill-policy-nodes": "Policy / procedure nodes to follow",
    "skill-grammar-sot": "Grammar source-of-truth (code-as-SSOT)",
    "skill-delivery": "Delivery surface",
    "skill-verify": "How to verify it landed",
    "skill-exec-refs": "Executable / reference pointers",
}


def compute_source_hash(projection: SkillProjection) -> str:
    """sha256 over the node's ``skill-*`` fields — the drift detector.

    Canonical: JSON with sorted keys and no incidental whitespace, so the same fields always
    hash the same regardless of scan/property ordering.
    """
    canonical = json.dumps(projection.skill_fields, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(canonical.encode("utf-8")).hexdigest()


#: X49: the explicit fail-closed instruction, emitted on every generated skill.
STOP_LINE = ("If the lts_node fetch fails or returns nothing, STOP and say so; "
             "never run from memory or this file.")


def liveness_warning(projection: SkillProjection) -> str | None:
    """The X49 liveness check, deliberately simple and deterministic (no clock):

    * the node carries NEITHER ``decided-in-session`` nor ``updated`` (a parseable ISO date) ->
      warn that its freshness cannot be told;
    * its newest such date is EARLIER than the newest dated lesson property it carries (a
      non-``skill-`` key ending in ``-YYYY-MM-DD``) -> warn that the node is older than a lesson
      it cites, so its owner may not have re-reviewed the procedure since.

    Otherwise None. The warning is rendered into the file body, NOT into ``source-hash``
    (which stays over the ``skill-*`` fields); reconcile therefore also compares rendered
    content, so a warning appears or clears on the next sync.
    """
    nid = projection.node_id
    if projection.node_date is None:
        return (f"WARNING (liveness): node [{nid}] carries no decided-in-session or updated date, "
                f"so its freshness cannot be told. Check the fetched node before trusting this skill.")
    if projection.lesson_date is not None and projection.node_date < projection.lesson_date:
        return (f"WARNING (liveness): node [{nid}] is dated {projection.node_date} but carries a lesson "
                f"property dated {projection.lesson_date}, so the node is older than a lesson it cites. "
                f"Read the dated lesson properties in the fetched node; the procedure may not have been "
                f"re-reviewed since.")
    return None


def _fm_escape(value: str) -> str:
    """Frontmatter values are single-line. Collapse newlines so a multi-line desc cannot
    break the frontmatter block or the line-based stamp parser."""
    return re.sub(r"\s+", " ", value).strip()


def render_skill(projection: SkillProjection) -> str:
    """Render the complete SKILL.md content for ``projection`` (deterministic)."""
    src_hash = compute_source_hash(projection)
    gen_from = f"{projection.node_id}@{projection.corpus}"

    lines: list[str] = []
    lines.append("---")
    lines.append(f"name: {projection.skill_name}")
    lines.append(f"description: {_fm_escape(projection.skill_desc)}")
    lines.append("user-invocable: true")
    lines.append(f"{STAMP_GENERATED_FROM}: {gen_from}")
    lines.append(f"{STAMP_SOURCE_HASH}: {src_hash}")
    lines.append("---")
    lines.append("")
    lines.append(_DO_NOT_EDIT)
    lines.append("")
    lines.append(f"# {projection.skill_name}")
    lines.append("")
    lines.append(
        f"Generated projection of [{projection.node_id}] in corpus `{projection.corpus}`. "
        f"The durable, current procedure lives in that node — this file is a pointer, not the source."
    )
    lines.append("")
    warning = liveness_warning(projection)
    if warning:
        lines.append(warning)
        lines.append("")
    if projection.skill_trigger:
        lines.append(f"**When to invoke:** {projection.skill_trigger}")
        lines.append("")
    lines.append(
        f"Query the projection contract for the full operating procedure: "
        f'`lts_node(corpus="{projection.corpus}", node_id="{projection.node_id}")`, then follow:'
    )
    lines.append("")
    if projection.pointers:
        for key, val in projection.pointers.items():
            label = _POINTER_LABEL.get(key, key)
            lines.append(f"- **{label}** (`{key}`): {val}")
    else:
        lines.append("- (the node carries no operational-pointer fields; read the node body directly)")
    lines.append("")
    lines.append(STOP_LINE)
    lines.append("")

    if projection.subset_today:
        lines.append("## Projected subset (operational today)")
        lines.append("")
        lines.append(projection.subset_today)
        lines.append("")
        if projection.subset_pending:
            lines.append(f"**Pending (NOT projected yet):** {projection.subset_pending}")
            lines.append("")
        if projection.what_changes_this:
            lines.append(f"**Re-projects when:** {projection.what_changes_this}")
            lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n"


@dataclass(frozen=True)
class Stamps:
    generated_from: str | None
    source_hash: str | None

    @property
    def is_generated(self) -> bool:
        return self.generated_from is not None


def _frontmatter_block(text: str) -> str | None:
    """Return the raw frontmatter block (between the first pair of ``---`` fences), or None."""
    m = re.match(r"^---\s*\n(.*?)\n---\s*(?:\n|$)", text, re.DOTALL)
    return m.group(1) if m else None


def parse_stamps(text: str) -> Stamps:
    """Extract the ownership/drift stamps from an existing SKILL.md.

    Reads ONLY the frontmatter block so body prose that happens to contain the token cannot
    be mistaken for a stamp. A file with no frontmatter, or frontmatter without the stamp,
    is treated as hand-authored (``generated_from is None``).
    """
    block = _frontmatter_block(text)
    if block is None:
        return Stamps(None, None)
    gen_from: str | None = None
    src_hash: str | None = None
    for line in block.splitlines():
        if ":" not in line:
            continue
        key, _, val = line.partition(":")
        key = key.strip()
        val = val.strip()
        if key == STAMP_GENERATED_FROM and val:
            gen_from = val
        elif key == STAMP_SOURCE_HASH and val:
            src_hash = val
    return Stamps(gen_from, src_hash)
