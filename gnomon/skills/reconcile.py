"""Reconcile the DESIRED projection set against what is on disk (constraint 2).

Per-skill classification:
  CREATE    — no ``<target>/<name>/`` directory at all
  UPDATE    — a generated file (stamped for the SAME corpus) whose ``source-hash`` stamp differs from
              desired, or whose stamp matches but whose RENDERED CONTENT differs (X49: the template
              or the liveness warning changed, or someone hand-edited a generated file)
  NOOP      — a generated file whose stamp AND content match desired
  CONFLICT  — a file exists WITHOUT a ``generated-from`` stamp (hand-authored) → do NOT touch
  COLLISION — (X49) the name is already taken by something that is not ours to write: a skill
              generated from ANOTHER corpus, a directory with no SKILL.md, a symlink, an
              unreadable file, or two projections claiming the same name → do NOT touch
  REFUSE    — the projection contract was malformed (never emit a broken file)

Directory-level:
  ORPHAN    — a ``generated-from`` file whose source node is no longer in the desired set
              (removed only under --apply --prune). With ``scope_corpora`` set, only orphans stamped
              for a corpus IN SCOPE are considered, so a run scoped to corpus A never reports (let
              alone prunes) corpus B's generated skills.

⛔ We touch ONLY files carrying a ``generated-from`` stamp for the corpus being synced. A
hand-authored skill (``statusline-setup`` etc.) is CONFLICT-reported and left untouched.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

from .contract import ContractError, SkillProjection
from .render import compute_source_hash, liveness_warning, parse_stamps, render_skill

SKILL_FILE = "SKILL.md"


class Action(enum.Enum):
    CREATE = "CREATE"
    UPDATE = "UPDATE"
    NOOP = "NOOP"
    CONFLICT = "CONFLICT"
    COLLISION = "COLLISION"
    REFUSE = "REFUSE"
    ORPHAN = "ORPHAN"


#: The actions that write a file (everything else is report-only, or a prune under --prune).
WRITE_ACTIONS = frozenset({Action.CREATE, Action.UPDATE})


@dataclass
class PlanEntry:
    action: Action
    skill_name: str | None
    node_id: str | None
    corpus: str | None
    path: Path
    detail: str
    rendered: str | None = None  # the content to write for CREATE/UPDATE
    warning: str | None = None   # the X49 liveness warning carried by the rendered file, if any

    def to_dict(self) -> dict:
        out = {
            "action": self.action.value,
            "skill_name": self.skill_name,
            "node_id": self.node_id,
            "corpus": self.corpus,
            "path": str(self.path),
            "detail": self.detail,
        }
        if self.warning:
            out["warning"] = self.warning
        return out


def _skill_path(target_dir: Path, skill_name: str) -> Path:
    return target_dir / skill_name / SKILL_FILE


def generated_corpus(generated_from: str | None) -> str | None:
    """The corpus part of a ``<node-id>@<corpus>`` stamp (None if the stamp has no ``@``)."""
    if not generated_from or "@" not in generated_from:
        return None
    return generated_from.rsplit("@", 1)[1].strip() or None


def _collision(projection: SkillProjection, path: Path, detail: str) -> PlanEntry:
    return PlanEntry(Action.COLLISION, projection.skill_name, projection.node_id, projection.corpus,
                     path, detail)


def classify_one(projection: SkillProjection, target_dir: Path) -> PlanEntry:
    """Classify a single validated projection against the filesystem."""
    skill_dir = target_dir / projection.skill_name
    path = _skill_path(target_dir, projection.skill_name)
    desired = render_skill(projection)
    desired_hash = compute_source_hash(projection)
    warn = liveness_warning(projection)

    if skill_dir.is_symlink() or path.is_symlink():
        return _collision(projection, path, "skill directory or SKILL.md is a symlink — NOT touched")
    if not skill_dir.exists():
        return PlanEntry(Action.CREATE, projection.skill_name, projection.node_id, projection.corpus,
                         path, "no existing file", rendered=desired, warning=warn)
    if not skill_dir.is_dir() or not path.is_file():
        return _collision(projection, path,
                          "the name is taken by a directory with no SKILL.md (not generated by us) — NOT touched")

    try:
        existing = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return _collision(projection, path, f"existing SKILL.md unreadable ({type(exc).__name__}) — NOT touched")
    stamps = parse_stamps(existing)
    if not stamps.is_generated:
        return PlanEntry(
            Action.CONFLICT, projection.skill_name, projection.node_id, projection.corpus, path,
            "file exists without a generated-from stamp (hand-authored) — NOT touched",
        )

    # Stamped. It is ours ONLY if it was generated from THIS projection's corpus.
    owner = generated_corpus(stamps.generated_from)
    if owner != projection.corpus:
        return _collision(
            projection, path,
            f"skill name already generated from {stamps.generated_from!r}, not corpus "
            f"{projection.corpus!r} — NOT touched")

    # Drift is decided by source-hash (spec §4), then by rendered content (X49).
    if stamps.source_hash == desired_hash:
        if existing == desired:
            return PlanEntry(Action.NOOP, projection.skill_name, projection.node_id, projection.corpus,
                             path, "source-hash and content match", rendered=desired, warning=warn)
        return PlanEntry(
            Action.UPDATE, projection.skill_name, projection.node_id, projection.corpus, path,
            "source-hash matches but rendered content differs (template/liveness change or hand edit)",
            rendered=desired, warning=warn)
    return PlanEntry(
        Action.UPDATE, projection.skill_name, projection.node_id, projection.corpus, path,
        f"source-hash drift ({stamps.source_hash} -> {desired_hash})", rendered=desired, warning=warn,
    )


@dataclass
class Plan:
    entries: list[PlanEntry]

    def by_action(self, action: Action) -> list[PlanEntry]:
        return [e for e in self.entries if e.action is action]

    def to_dict(self) -> dict:
        counts: dict[str, int] = {}
        for e in self.entries:
            counts[e.action.value] = counts.get(e.action.value, 0) + 1
        return {"counts": counts, "entries": [e.to_dict() for e in self.entries]}


def _find_orphans(desired_names: set[str], target_dir: Path,
                  scope_corpora: frozenset[str] | None) -> list[PlanEntry]:
    """A ``generated-from`` file on disk whose skill-name is not in the desired set is an orphan
    (only when stamped for a corpus in ``scope_corpora``, if that is set)."""
    orphans: list[PlanEntry] = []
    if not target_dir.exists():
        return orphans
    for child in sorted(target_dir.iterdir()):
        if child.is_symlink() or not child.is_dir():
            continue
        name = child.name
        if name in desired_names:
            continue
        skill_file = child / SKILL_FILE
        if skill_file.is_symlink() or not skill_file.is_file():
            continue
        try:
            stamps = parse_stamps(skill_file.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError):
            continue
        if not stamps.is_generated:
            continue
        if scope_corpora is not None and generated_corpus(stamps.generated_from) not in scope_corpora:
            continue  # another corpus's generated skill: not ours to report or prune
        orphans.append(PlanEntry(
            Action.ORPHAN, name, None, None, skill_file,
            f"generated-from={stamps.generated_from} but source node no longer in scan",
        ))
    return orphans


def classify(
    projections: list[SkillProjection],
    refusals: list[ContractError],
    target_dir: Path,
    scope_corpora: Iterable[str] | None = None,
) -> Plan:
    """Build the full reconcile plan: per-projection classification + refusals + orphans."""
    scope = frozenset(scope_corpora) if scope_corpora is not None else None
    entries: list[PlanEntry] = []
    desired_names: set[str] = set()

    by_name: dict[str, list[SkillProjection]] = {}
    for proj in projections:
        by_name.setdefault(proj.skill_name, []).append(proj)

    for proj in projections:
        desired_names.add(proj.skill_name)
        claimants = by_name[proj.skill_name]
        if len(claimants) > 1:
            who = ", ".join(sorted(f"{p.node_id}@{p.corpus}" for p in claimants))
            entries.append(_collision(proj, _skill_path(target_dir, proj.skill_name),
                                      f"duplicate skill-name claimed by several nodes ({who}) — none written"))
            continue
        try:
            entries.append(classify_one(proj, target_dir))
        except OSError as exc:
            # X49 F-1: a filesystem error on ONE name (e.g. a name the OS rejects) refuses that skill
            # only; it must not abort the plan for the rest of the corpus.
            entries.append(PlanEntry(
                Action.REFUSE, proj.skill_name, proj.node_id, proj.corpus,
                _skill_path(target_dir, proj.skill_name),
                f"filesystem error classifying this skill ({type(exc).__name__}: {exc}) — NOT touched"))

    for err in refusals:
        name = err.skill_name
        path = _skill_path(target_dir, name) if name else target_dir
        entries.append(PlanEntry(
            Action.REFUSE, name, err.node_id, None, path,
            f"malformed projection contract: {err.reason}",
        ))
        # A refused skill is NOT part of the desired set, so it does not protect a same-named
        # file from being flagged an orphan — but if the file is hand-authored the orphan
        # scan skips it (no generated-from), and if it is ours we would rather leave it than
        # prune on a malformed contract. Guard: keep any same-named dir out of orphan scope.
        if name:
            desired_names.add(name)

    entries.extend(_find_orphans(desired_names, target_dir, scope))
    return Plan(entries)
